#!/usr/bin/env python3
"""Generate a local stand-in for an `api-ms-win-*` contract that Windows 7
cannot satisfy.

Windows 7 resolves an API-set name through its own ApiSetSchema first.  When
the contract is missing (or maps to a host that does not export the function)
the loader reports

    The procedure entry point GetACP could not be located in the dynamic link
    library api-ms-win-core-localization-l1-2-0.dll

If the contract is *not* in Win7's schema the loader falls back to the normal
DLL search, so a file of that name in the application folder is used - which
is what this script produces: a DLL that exports every function anybody might
import from the contract, resolved lazily from kernel32/kernelbase/ntdll/...

Missing symbols degrade to a logged stub instead of failing the load, so the
shim is safe to ship even if we do not know the exact export list a given
machine needs.

Usage:
  gen_apiset_shim.py <api-ms-win-....dll> --out DIR [--extra name,name]
"""
import argparse
import os
import sys

# NLS / localization functions (the contract reported broken on the target
# machine was api-ms-win-core-localization-l1-2-0 -> GetACP).  Lazy lookup
# makes an over-long list harmless.
DEFAULT_FUNCS = """
GetACP GetOEMCP GetCPInfo GetCPInfoExW GetConsoleCP GetConsoleOutputCP
GetLocaleInfoA GetLocaleInfoW GetLocaleInfoExW SetLocaleInfoW
LocaleNameToLCID LCIDToLocaleName GetLcidFromLocaleName
LCMapStringA LCMapStringW LCMapStringEx CompareStringA CompareStringW
CompareStringEx CompareStringOrdinal
GetUserDefaultLCID GetSystemDefaultLCID GetUserDefaultLocaleName
GetSystemDefaultLocaleName GetThreadLocale SetThreadLocale
GetUserDefaultLangID GetSystemDefaultLangID GetUserDefaultUILanguage
GetSystemDefaultUILanguage IsValidLocale IsValidLocaleName IsValidLanguage
EnumSystemLocalesA EnumSystemLocalesW EnumSystemLocalesEx
EnumSystemLanguageGroupsW GetLanguageName
GetDateFormatA GetDateFormatW GetDateFormatEx GetTimeFormatA GetTimeFormatW
GetTimeFormatEx GetCalendarInfoW GetCalendarInfoEx
GetGeoInfoW GetUserGeoID SetUserGeoID IsValidCodePage
GetOEMCP GetACP""".split()

HOST_K32 = 0  # kernel32 -> kernelbase -> ntdll  (see src/win7shim/win7shim.c)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dll_name", help="output DLL file name, e.g. "
                                     "api-ms-win-core-localization-l1-2-0.dll")
    ap.add_argument("--out", required=True)
    ap.add_argument("--extra", default="", help="comma separated extra exports")
    args = ap.parse_args()

    funcs = list(dict.fromkeys(DEFAULT_FUNCS))  # order preserving dedup
    if args.extra:
        funcs += [f for f in args.extra.split(",") if f and f not in funcs]

    os.makedirs(args.out, exist_ok=True)
    n = len(funcs)

    inc = ["/* generated by scripts/gen_apiset_shim.py - do not edit */",
           "#pragma once", "",
           "typedef struct { const char* name; unsigned char host; } GenEnt;", "",
           "static const GenEnt GEN[] = {"]
    for f in funcs:
        inc.append('    { "%s", %d },' % (f, HOST_K32))
    inc.append("};")
    inc.append("static const unsigned GEN_N = %d;" % n)
    open(os.path.join(args.out, "win7shim_names.inc"), "w").write(
        "\n".join(inc) + "\n")

    asm = ["/* generated by scripts/gen_apiset_shim.py - do not edit */",
           "\t.text", "\t.p2align 4"]
    for i in range(n):
        asm += ["\t.globl t_%d" % i, "t_%d:" % i,
                "\tjmp *win7shim_slots+%d(%%rip)" % (i * 8)]
    asm += ["", "\t.data", "\t.p2align 3", "\t.globl win7shim_slots",
            "win7shim_slots:"]
    asm += ["\t.quad 0"] * n
    open(os.path.join(args.out, "win7shim_gen.S"), "w").write(
        "\n".join(asm) + "\n")

    deff = ['LIBRARY "%s"' % os.path.splitext(args.dll_name)[0], "EXPORTS"]
    deff += ["%s=t_%d" % (f, i) for i, f in enumerate(funcs)]
    open(os.path.join(args.out, "win7shim.def"), "w").write(
        "\n".join(deff) + "\n")

    print("gen_apiset_shim: %s with %d exports -> %s"
          % (args.dll_name, n, args.out))


if __name__ == "__main__":
    main()
