#!/usr/bin/env python3
"""Make the official onnxruntime.dll loadable on Windows 7.

The official ONNX Runtime 1.14.1 Windows binary was built against Windows 8+
api-set contracts.  It statically imports:

  api-ms-win-core-file-l1-2-0     -> CreateFile2              (Windows 8+)
  api-ms-win-core-sysinfo-l1-2-0  -> GetSystemTimePreciseAsFileTime (Windows 8+)
  api-ms-win-core-path-l1-1-0     -> PathCchRemove*           (Windows 8.1+/KB2999226)
  (+ 30 more api-ms-win-* contracts)

Windows 7's API-set schema does not know those contracts, so any process that
*statically imports* onnxruntime.dll dies while the loader is still
initialiating it - before main() ever runs - typically with

    The application was unable to start correctly (0xc0000005)

which is exactly what happened on the target Windows 7 SP1 machine.

This script:
  1. rewrites every `api-ms-win-*` import descriptor of the DLL so that it
     names a local `w7shim.dll` instead (the name string of one existing
     api-set descriptor is overwritten in place and reused, so the file size
     does not change);
  2. generates the shim sources (`win7shim_gen.S`, `win7shim_names.inc`,
     `win7shim.def`) which re-export every affected function, resolved at
     run time from the DLLs that really exist on Windows 7
     (kernel32/kernelbase/ntdll/advapi32/ucrtbase/msvcrt), and implement the
     four Windows-8-only functions themselves.

The shim never resolves anything eagerly at load time - each export is a
trampoline whose target is looked up on first use - so the presence or
absence of a single symbol can never fail the process startup again.

Idempotent: running it on an already-patched DLL only regenerates the shim
sources.

Usage:
  scripts/patch_ort_win7.py <onnxruntime.dll> --shim-out <dir> [--dll-name w7shim.dll]
"""
import argparse
import os
import struct
import sys

import pefile

# Windows-8+ functions that simply do not exist on Windows 7: implemented by
# hand inside w7shim.dll.
CUSTOM = {
    "GetSystemTimePreciseAsFileTime",
    "CreateFile2",
    "PathCchRemoveBackslash",
    "PathCchRemoveFileSpec",
}

# host ids shared with src/win7shim/win7shim.c
HOST_K32 = 0   # kernel32 -> kernelbase -> ntdll
HOST_CRT = 1   # ucrtbase -> msvcrt
HOST_NTDLL = 2
HOST_ADVAPI = 3
HOST_CUSTOM = 4

SHIM_DEF_NAME = "w7shim.dll"


def classify(api_set: str, func: str) -> int:
    # Windows-8+ functions are still resolved through the kernel32 chain first
    # (a Windows 10 machine or Wine has them); w7shim falls back to its own
    # implementation when the chain comes up empty, which is what happens on
    # Windows 7.
    if func in CUSTOM:
        return HOST_K32
    s = api_set.lower()
    if s.startswith("api-ms-win-crt-"):
        return HOST_CRT
    if "rtlsupport" in s:
        return HOST_NTDLL
    if "eventing-provider" in s:
        return HOST_ADVAPI
    return HOST_K32


def collect_all(pe):
    """[(descriptor_index, dll_name, [functions...]), ...] in table order."""
    out = []
    for idx, desc in enumerate(pe.DIRECTORY_ENTRY_IMPORT):
        name = desc.dll.decode("ascii", "replace")
        funcs = []
        for entry in desc.imports:
            if entry.name:
                funcs.append(entry.name.decode("ascii", "replace"))
            else:
                funcs.append("#%d" % entry.ordinal)
        out.append((idx, name, funcs))
    return out


def collect(pe):
    """[(descriptor_index, api_set_name, [functions...]), ...] in table order."""
    return [e for e in collect_all(pe) if e[1].lower().startswith("api-ms-win-")]


def generate_shim(out_dir, entries, dll_name):
    """entries: [(api_set, func, host)] in the order used for the trampolines."""
    os.makedirs(out_dir, exist_ok=True)
    n = len(entries)

    lines = ["/* generated by scripts/patch_ort_win7.py - do not edit */",
             "#pragma once", "",
             "typedef struct { const char* name; unsigned char host; } GenEnt;", "",
             "static const GenEnt GEN[] = {"]
    for api_set, func, host in entries:
        lines.append('    { "%s", %d },  /* from %s */' % (func, host, api_set))
    lines.append("};")
    lines.append("static const unsigned GEN_N = %d;" % n)
    lines.append("")
    with open(os.path.join(out_dir, "win7shim_names.inc"), "w") as f:
        f.write("\n".join(lines) + "\n")

    asm = ["/* generated by scripts/patch_ort_win7.py - do not edit */",
           "\t.text", "\t.p2align 4"]
    for i in range(n):
        asm.append("\t.globl t_%d" % i)
        asm.append("t_%d:" % i)
        asm.append("\tjmp *win7shim_slots+%d(%%rip)" % (i * 8))
    asm += ["", "\t.data", "\t.p2align 3", "\t.globl win7shim_slots",
            "win7shim_slots:"]
    for i in range(n):
        asm.append("\t.quad 0")
    asm.append("")
    with open(os.path.join(out_dir, "win7shim_gen.S"), "w") as f:
        f.write("\n".join(asm) + "\n")

    deff = ["LIBRARY \"%s\"" % os.path.splitext(dll_name)[0], "EXPORTS"]
    for i, (_, func, _) in enumerate(entries):
        deff.append("%s=t_%d" % (func, i))
    deff.append("")
    with open(os.path.join(out_dir, "win7shim.def"), "w") as f:
        f.write("\n".join(deff) + "\n")
    return n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dll", help="path to onnxruntime.dll (patched in place)")
    ap.add_argument("--shim-out", required=True, help="directory for generated shim sources")
    ap.add_argument("--dll-name", default=SHIM_DEF_NAME)
    args = ap.parse_args()

    pe = pefile.PE(args.dll)
    entries_desc = collect(pe)
    if not entries_desc:
        print("patch_ort_win7: no api-ms-win-* imports found (already patched), "
              "regenerating shim only")
        # regenerate from the shim name itself: read the function list from the
        # previous run's names file if present, otherwise nothing to do.
        inc = os.path.join(args.shim_out, "win7shim_names.inc")
        if not os.path.exists(inc):
            raise SystemExit("patch_ort_win7: no previous shim sources found at " + inc)
        entries = []
        for line in open(inc):
            line = line.strip()
            if line.startswith('{ "'):
                func = line.split('"')[1]
                host = int(line.split(",")[1].split("}")[0])
                src = ""
                if " from " in line:
                    src = line.split(" from ", 1)[1].split(" */")[0].strip()
                entries.append((src or "api-ms-win-", func,
                                classify(src, func) if src else host))
        n = generate_shim(args.shim_out, entries, args.dll_name)
        print("patch_ort_win7: regenerated shim with %d exports" % n)
        return

    # --- find the import descriptor table -------------------------------
    imp = pe.OPTIONAL_HEADER.DATA_DIRECTORY[
        pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_IMPORT"]]
    if imp.VirtualAddress == 0:
        raise SystemExit("patch_ort_win7: no import directory")
    table_off = pe.get_offset_from_rva(imp.VirtualAddress)
    desc_size = 20

    # --- pick the api-set name string we will overwrite ------------------
    api_idx = {idx for idx, _, _ in entries_desc}
    # the string with the longest name (>= len("w7shim.dll\0"))
    best_rva, best_len = None, -1
    for idx, name, _ in entries_desc:
        rva = pe.DIRECTORY_ENTRY_IMPORT[idx].struct.Name
        end = pe.get_offset_from_rva(rva)
        raw = pe.__data__[end:end + 128]
        slen = raw.index(b"\0") if b"\0" in raw else len(raw)
        if slen > best_len:
            best_rva, best_len = rva, slen
    if best_len < len(args.dll_name) + 1:
        raise SystemExit("patch_ort_win7: chosen name string too short (%d)" % best_len)
    if pe.__data__[pe.get_offset_from_rva(best_rva):
                   pe.get_offset_from_rva(best_rva) + best_len + 1].count(b"w7shim") == 0:
        pass  # not patched yet (or patched under another name) - overwrite below

    already = pe.__data__[pe.get_offset_from_rva(best_rva):][:10] == b"w7shim.dll"

    # --- rewrite the descriptors and the shared name string on raw bytes -
    # (pefile's write() silently drops set_bytes_at_* edits, so patch a plain
    #  byte buffer instead)
    with open(args.dll, "rb") as f:
        data = bytearray(f.read())
    shim_name = args.dll_name.encode("ascii") + b"\0"
    name_off = pe.get_offset_from_rva(best_rva)
    if name_off + len(shim_name) > len(data):
        raise SystemExit("patch_ort_win7: name string out of range")
    for idx, name, funcs in entries_desc:
        off = table_off + idx * desc_size + 12  # IMAGE_IMPORT_DESCRIPTOR.Name
        struct.pack_into("<I", data, off, best_rva)
    data[name_off:name_off + len(shim_name)] = shim_name

    # --- verify before writing ------------------------------------------
    tmp = args.dll + ".patched"
    with open(tmp, "wb") as f:
        f.write(data)
    pe2 = pefile.PE(tmp)
    before = collect_all(pefile.PE(args.dll))
    after = collect_all(pe2)
    if len(after) != len(before):
        raise SystemExit("patch_ort_win7: descriptor count changed!")
    for (i1, n1, f1), (i2, n2, f2) in zip(before, after):
        if i1 != i2 or f1 != f2:
            raise SystemExit("patch_ort_win7: descriptor %d functions changed (%s)"
                             % (i1, n1))
        if n1.lower().startswith("api-ms-win-"):
            if n2.lower() != args.dll_name.lower():
                raise SystemExit("patch_ort_win7: descriptor %d not rewritten (%s)"
                                 % (i1, n2))
        elif n1 != n2:
            raise SystemExit("patch_ort_win7: non api-set import changed (%s)" % n1)
    if os.path.getsize(tmp) != os.path.getsize(args.dll):
        raise SystemExit("patch_ort_win7: file size changed")
    os.replace(tmp, args.dll)

    # --- generate the shim ------------------------------------------------
    entries = []
    for _, api_set, funcs in entries_desc:
        for fn in funcs:
            entries.append((api_set, fn, classify(api_set, fn)))
    # de-duplicate while keeping order (a function may appear in 2 sets)
    seen, uniq = set(), []
    for e in entries:
        if e[1] in seen:
            if classify("api-ms-win-x", e[1]) != e[2]:
                raise SystemExit("patch_ort_win7: conflicting hosts for %s" % e[1])
            continue
        seen.add(e[1])
        uniq.append(e)
    n = generate_shim(args.shim_out, uniq, args.dll_name)

    print("patch_ort_win7: rewrote %d api-set import descriptors of %s -> %s"
          % (len(entries_desc), os.path.basename(args.dll), args.dll_name))
    print("patch_ort_win7: generated shim with %d exports in %s" % (n, args.shim_out))
    for idx, api_set, funcs in entries_desc:
        print("    %-40s %3d functions" % (api_set, len(funcs)))


if __name__ == "__main__":
    main()
