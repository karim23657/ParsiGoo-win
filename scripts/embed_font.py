#!/usr/bin/env python3
"""Embed a TrueType font into a C header (used by the Win32 GUI).

    scripts/embed_font.py /content/sahel.ttf src/sahel_font.h

The GUI calls AddFontMemResourceEx() on the array so the UI can use Sahel on
any machine, with no separate .ttf to forget to copy. The font can still be
replaced at run time by putting a sahel.ttf next to the exe (that one is
loaded first).
"""
import sys
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    data = src.read_bytes()
    if len(data) < 4 or data[:4] not in (b"\x00\x01\x00\x00", b"true", b"OTTO", b"ttcf"):
        print(f"{src}: not a TrueType/OpenType font", file=sys.stderr)
        return 1

    out = [
        "// Generated by scripts/embed_font.py — do not edit by hand.",
        f"// font: {src.name}, {len(data)} bytes",
        "#pragma once",
        "",
        "// Sahel (c) Saber Rastikerdar, SIL Open Font License 1.1 — embedded so",
        "// the GUI can use it on any Windows install without shipping the file.",
        f"static const unsigned char kFontData[{len(data)}] = {{",
    ]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        out.append("    " + ",".join(f"0x{b:02x}" for b in chunk) + ",")
    out.append("};")
    out.append(f"static const unsigned kFontDataLen = {len(data)};")
    out.append("")
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("\n".join(out), encoding="utf-8")
    print(f"{dst}: {len(data)} bytes -> {dst.stat().st_size} byte header")
    return 0


if __name__ == "__main__":
    sys.exit(main())
